/**
 * Build a section of seats. `perRow` seats per row across the given row labels,
 * with an aisle gap after `aisleAfter`. A deterministic pattern marks some seats
 * sold so the demo map looks realistically partly-booked.
 */
function makeSection(id: string, name: string, rowLabels: string[], perRow: number, aisleAfter: number): SeatSection {
  const rows: SeatRow[] = rowLabels.map((label, rowIdx) => {
    const seats: SeatRow["seats"] = [];
    for (let n = 1; n <= perRow; n++) {
      // Deterministic "already sold" scatter.
      const sold = (rowIdx * 7 + n * 3) % 11 === 0 || (rowIdx + n) % 9 === 0;
      seats.push({ id: `${id}-${label}${n}`, status: sold ? "sold" : "available" });
      if (n === aisleAfter) seats.push(null); // aisle gap
    }
    return { label, seats };
  });
  return { id, name, rows };
}

